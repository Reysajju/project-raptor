"use client";

import * as React from "react";
import { Sparkles, Loader2, X, Wand2, Copy, Check } from "lucide-react";
import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogFooter,
} from "@/components/ui/dialog";
import { Textarea } from "@/components/ui/textarea";
import { Label } from "@/components/ui/label";
import { Badge } from "@/components/ui/badge";
import { apiPost } from "@/components/portal/query-hooks";
import { toast } from "sonner";
import { cn } from "@/lib/utils";

interface AiSummaryDialogProps {
  clientId: string;
  open: boolean;
  onOpenChange: (v: boolean) => void;
}

export function AiSummaryDialog({ clientId, open, onOpenChange }: AiSummaryDialogProps) {
  const [loading, setLoading] = React.useState(false);
  const [summary, setSummary] = React.useState<string | null>(null);

  const generate = React.useCallback(async () => {
    setLoading(true);
    setSummary(null);
    try {
      const res = await apiPost<{ summary: string }>("/api/portal/ai/summarize", { clientId });
      setSummary(res.summary);
    } catch (err) {
      toast.error("Failed to generate summary", { description: (err as Error).message });
    } finally {
      setLoading(false);
    }
  }, [clientId]);

  React.useEffect(() => {
    if (open && !summary && !loading) {
      generate();
    }
    if (!open) {
      // reset on close
      setTimeout(() => {
        setSummary(null);
        setLoading(false);
      }, 200);
    }
  }, [open, summary, loading, generate]);

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="max-w-lg">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2 text-base">
            <span className="flex h-7 w-7 items-center justify-center rounded-md bg-accent text-accent-foreground">
              <Sparkles className="h-4 w-4" />
            </span>
            AI thread summary
          </DialogTitle>
        </DialogHeader>
        <div className="min-h-[120px]">
          {loading ? (
            <div className="flex flex-col items-center justify-center gap-3 py-10">
              <Loader2 className="h-6 w-6 animate-spin text-primary" />
              <p className="text-sm text-muted-foreground">Analyzing the last 30 messages…</p>
            </div>
          ) : summary ? (
            <div className="space-y-3">
              <div className="whitespace-pre-wrap rounded-lg border border-border bg-muted/40 p-4 text-sm leading-relaxed">
                {summary}
              </div>
              <div className="flex items-center justify-between">
                <Badge variant="secondary" className="text-[10px]">
                  Generated by AI · review before acting
                </Badge>
                <Button variant="ghost" size="sm" className="h-7 gap-1 text-xs" onClick={generate}>
                  <Wand2 className="h-3 w-3" /> Regenerate
                </Button>
              </div>
            </div>
          ) : (
            <p className="py-10 text-center text-sm text-muted-foreground">
              Click generate to summarize the thread.
            </p>
          )}
        </div>
        <DialogFooter>
          <Button variant="outline" size="sm" onClick={() => onOpenChange(false)}>
            Close
          </Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}

interface AiDraftButtonProps {
  clientId: string;
  channel: string;
  onApply: (draft: string) => void;
  className?: string;
}

export function AiDraftButton({ clientId, channel, onApply, className }: AiDraftButtonProps) {
  const [open, setOpen] = React.useState(false);
  const [loading, setLoading] = React.useState(false);
  const [draft, setDraft] = React.useState<string | null>(null);
  const [instruction, setInstruction] = React.useState("");
  const [copied, setCopied] = React.useState(false);

  const generate = React.useCallback(async () => {
    setLoading(true);
    setDraft(null);
    try {
      const res = await apiPost<{ draft: string }>("/api/portal/ai/draft-reply", {
        clientId,
        instruction: instruction.trim() || undefined,
        channel,
      });
      setDraft(res.draft);
    } catch (err) {
      toast.error("Failed to generate draft", { description: (err as Error).message });
    } finally {
      setLoading(false);
    }
  }, [clientId, instruction, channel]);

  const apply = () => {
    if (draft) {
      onApply(draft);
      setOpen(false);
      setDraft(null);
      setInstruction("");
      toast.success("Draft applied to composer");
    }
  };

  const copy = async () => {
    if (!draft) return;
    try {
      await navigator.clipboard.writeText(draft);
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    } catch {
      toast.error("Couldn't copy");
    }
  };

  return (
    <>
      <Button
        type="button"
        variant="outline"
        size="sm"
        className={cn("gap-1.5 border-accent/40 text-accent-foreground hover:bg-accent/40", className)}
        onClick={() => setOpen(true)}
        title="Draft a reply with AI"
      >
        <Sparkles className="h-3.5 w-3.5" />
        AI draft
      </Button>
      <Dialog open={open} onOpenChange={(v) => { setOpen(v); if (!v) { setDraft(null); setInstruction(""); } }}>
        <DialogContent className="max-w-lg">
          <DialogHeader>
            <DialogTitle className="flex items-center gap-2 text-base">
              <span className="flex h-7 w-7 items-center justify-center rounded-md bg-accent text-accent-foreground">
                <Wand2 className="h-4 w-4" />
              </span>
              AI reply draft
              <Badge variant="secondary" className="ml-1 text-[10px] capitalize">{channel}</Badge>
            </DialogTitle>
          </DialogHeader>
          <div className="space-y-3">
            <div className="space-y-1.5">
              <Label htmlFor="ai-instruction" className="text-xs text-muted-foreground">
                Instruction (optional)
              </Label>
              <Textarea
                id="ai-instruction"
                value={instruction}
                onChange={(e) => setInstruction(e.target.value)}
                placeholder="e.g. confirm the Thursday call, mention the addendum is ready"
                className="min-h-[60px] resize-none text-sm"
                rows={2}
              />
            </div>
            <Button
              size="sm"
              className="w-full gap-2"
              onClick={generate}
              disabled={loading}
            >
              {loading ? (
                <>
                  <Loader2 className="h-4 w-4 animate-spin" /> Drafting…
                </>
              ) : (
                <>
                  <Sparkles className="h-4 w-4" /> {draft ? "Regenerate draft" : "Generate draft"}
                </>
              )}
            </Button>
            {draft && (
              <div className="space-y-2">
                <div className="relative rounded-lg border border-border bg-muted/40 p-3 text-sm leading-relaxed whitespace-pre-wrap max-h-[240px] overflow-y-auto scrollbar-thin">
                  {draft}
                </div>
                <div className="flex items-center justify-between">
                  <Button variant="ghost" size="sm" className="h-7 gap-1 text-xs" onClick={copy}>
                    {copied ? <Check className="h-3 w-3" /> : <Copy className="h-3 w-3" />}
                    {copied ? "Copied" : "Copy"}
                  </Button>
                  <Button size="sm" className="h-7 gap-1 text-xs" onClick={apply}>
                    <Check className="h-3 w-3" /> Apply to composer
                  </Button>
                </div>
              </div>
            )}
          </div>
        </DialogContent>
      </Dialog>
    </>
  );
}
